def main():
    with open(TARGET_FILE, 'r', encoding='utf-8') as f:
        lines = f.readlines()

    total_lines = len(lines)
    print(f"Total lines in {TARGET_FILE}: {total_lines}")
    assert total_lines == 110622, f"Unexpected line count: {total_lines}"

    start_idx = START_LINE - 1
    end_idx = END_LINE

    assert end_idx - start_idx == EXPECTED_COUNT, f"Count mismatch: {end_idx - start_idx} vs {EXPECTED_COUNT}"

    for i, pol_text in enumerate(POLISHED_LINES):
        line_idx = start_idx + i
        orig_line = lines[line_idx]
        parts = orig_line.rstrip('\r\n').split('\t')
        assert len(parts) >= 2, f"Line {line_idx+1} has no tab: {orig_line}"
        line_id = parts[0]
        lines[line_idx] = f"{line_id}\t{pol_text}\n"

    with open(TARGET_FILE, 'w', encoding='utf-8') as f:
        f.writelines(lines)

    print(f"Successfully patched {EXPECTED_COUNT} lines in {TARGET_FILE} (lines {START_LINE}-{END_LINE}).")

if __name__ == '__main__':
    main()
