def apply_patch():
    file_path = os.path.join(os.path.dirname(__file__), "..", "ALL_TEXT_cn.txt")
    with open(file_path, "r", encoding="utf-8") as f:
        lines = f.readlines()
    
    print(f"Total lines before patch: {len(lines)}")
    assert len(lines) == 110622, f"Expected 110622 lines, got {len(lines)}"
    
    modified_count = 0
    for line_num, (tag, new_text) in MODIFICATIONS.items():
        idx = line_num - 1
        curr_line = lines[idx]
        parts = curr_line.rstrip("\r\n").split("\t")
        if curr_line.strip() == "" and new_text == "":
            continue
        assert len(parts) == 2, f"Line {line_num} does not have 2 parts: {curr_line}"
        curr_tag, curr_text = parts
        assert curr_tag == tag, f"Line {line_num} tag mismatch: expected {tag}, got {curr_tag}"
        
        if curr_text != new_text:
            lines[idx] = f"{curr_tag}\t{new_text}\n"
            modified_count += 1
            
    print(f"Total modifications applied: {modified_count}")
    with open(file_path, "w", encoding="utf-8") as f:
        f.writelines(lines)
    print("Patch applied successfully!")

if __name__ == "__main__":
    apply_patch()
