def apply_com02():
    start_line = 12576
    end_line = 12812
    total = end_line - start_line + 1

    with open("ALL_TEXT.txt", "r", encoding="utf-8") as fj:
        ja_lines = [fj.readline().rstrip("\r\n") for _ in range(end_line)][start_line - 1 : end_line]

    with open("ALL_TEXT_cn.txt", "r", encoding="utf-8") as fc:
        cn_all = [l.rstrip("\r\n") for l in fc]

    patched_cn = []
    modifications = []

    for idx in range(total):
        orig_ja = ja_lines[idx]
        orig_cn = cn_all[start_line - 1 + idx]
        line_no = start_line + idx

        j_id, j_text = orig_ja.split("\t", 1)
        c_id, c_text = orig_cn.split("\t", 1)
        assert j_id == c_id, f"ID mismatch at line {line_no}: {j_id} != {c_id}"

        new_text = COM02_TRANSLATIONS[idx]
        new_line = f"{c_id}\t{new_text}"
        patched_cn.append(new_line)

        if new_text != c_text:
            modifications.append({
                "line": line_no,
                "id": c_id,
                "ja": j_text,
                "old": c_text,
                "new": new_text
            })

    backup_path = "ALL_TEXT_cn.txt.bak"
    shutil.copyfile("ALL_TEXT_cn.txt", backup_path)

    cn_all[start_line - 1 : end_line] = patched_cn
    with open("ALL_TEXT_cn.txt", "w", encoding="utf-8") as fw:
        for l in cn_all:
            fw.write(l + "\n")

    if verify():
        print(f"[SUCCESS] Patched grisaia1/com02 ({len(modifications)} / {total} lines modified). Verification passed!")
        if os.path.exists(backup_path):
            os.remove(backup_path)
        return modifications
    else:
        print("[FAIL] Verification failed! Rolling back...")
        shutil.copyfile(backup_path, "ALL_TEXT_cn.txt")
        return None

