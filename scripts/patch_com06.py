    assert len(polished_texts) == 203, f"Mismatch: expected 203 lines, got {len(polished_texts)}"

    # Patch lines
    for idx, (target_line_idx, new_text) in enumerate(zip(range(start_idx, end_idx), polished_texts)):
        line_id = lines[target_line_idx].split('\t')[0]
        lines[target_line_idx] = f"{line_id}\t{new_text}\n"

    with open(cn_file, 'w', encoding='utf-8') as f:
        f.writelines(lines)

    print(f"Successfully patched {len(polished_texts)} lines in {cn_file} from line {start_idx + 1} to {end_idx}.")

