def verify_speakers(dump_file):
    with open(dump_file, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    mismatches = 0
    for row in data:
        lno = row['line']
        if lno in PATCHES:
            patch_txt = PATCHES[lno]
            patch_sp = ''
            if patch_txt.startswith('@') and '@' in patch_txt[1:]:
                patch_sp = patch_txt.split('@', 2)[1]
            orig_sp = row['cn_sp']
            if patch_sp != orig_sp:
                print(f"[ERROR] Speaker mismatch at line {lno}: patch '{patch_sp}' != orig '{orig_sp}'")
                mismatches += 1
    return mismatches

def apply_patches(cn_file):
    with open(cn_file, 'r', encoding='utf-8') as f:
        lines = f.readlines()
    
    count = 0
    for lno, new_text in PATCHES.items():
        idx = lno - 1
        line = lines[idx]
        parts = line.split('\t', 1)
        if len(parts) == 2:
            tag = parts[0]
            lines[idx] = f"{tag}\t{new_text}\n"
            count += 1
        else:
            print(f"[ERROR] Malformed line {lno}: {line.strip()}")
            sys.exit(1)
            
    with open(cn_file, 'w', encoding='utf-8') as f:
        f.writelines(lines)
    print(f"Applied {count} patches to {cn_file}")

if __name__ == '__main__':
    errs = verify_speakers('tmp/mic_008_dump.json')
    if errs > 0:
        print(f"Aborting due to {errs} speaker mismatches.")
        sys.exit(1)
    apply_patches('ALL_TEXT_cn.txt')
