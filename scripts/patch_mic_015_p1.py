def main():
    with open("ALL_TEXT_cn.txt", "r", encoding="utf-8") as f:
        lines = f.readlines()

    applied = 0
    for lno, text in POLISHED.items():
        idx = lno - 1
        raw = lines[idx].rstrip("\r\n")
        if "\t" in raw:
            sid, _ = raw.split("\t", 1)
            lines[idx] = f"{sid}\t{text}\n"
        else:
            if text == "" and raw == "":
                lines[idx] = "\n"
            else:
                lines[idx] = f"{text}\n"
        applied += 1

    with open("ALL_TEXT_cn.txt", "w", encoding="utf-8") as f:
        f.writelines(lines)

    print(f"Successfully applied {applied} patches to ALL_TEXT_cn.txt")

if __name__ == "__main__":
    main()
