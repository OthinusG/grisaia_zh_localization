def apply_patch():
    with open("ALL_TEXT_cn.txt", "r", encoding="utf-8") as f:
        lines = f.readlines()

    patched_count = 0
    for lno, new_text in changes.items():
        idx = lno - 1
        raw = lines[idx]
        if "\t" in raw:
            sid, _ = raw.split("\t", 1)
            lines[idx] = f"{sid}\t{new_text}\n"
        else:
            lines[idx] = f"{new_text}\n"
        patched_count += 1

    with open("ALL_TEXT_cn.txt", "w", encoding="utf-8") as f:
        f.writelines(lines)

    print(f"Patched {patched_count} lines in ALL_TEXT_cn.txt.")

