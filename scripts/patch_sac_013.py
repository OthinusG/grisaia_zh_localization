def apply_patch():
    file_path = 'ALL_TEXT_cn.txt'
    with open(file_path, 'r', encoding='utf-8') as f:
        lines = f.readlines()

    total_lines = len(lines)
    assert total_lines == 110622, f'Expected 110622 lines, got {total_lines}'

    modified_count = 0
    for line_no, (expected_id, new_text) in MODIFICATIONS.items():
        idx = line_no - 1
        line = lines[idx]
        if expected_id:
            assert expected_id in line, f'ID mismatch at line {line_no}: expected {expected_id}, found {line[:30]}'
            prefix, _ = line.rstrip('\r\n').split('\t', 1)
            lines[idx] = f'{prefix}\t{new_text}\n'
        else:
            lines[idx] = f'{new_text}\n'
        modified_count += 1

    with open(file_path, 'w', encoding='utf-8') as f:
        f.writelines(lines)

    print(f'Successfully patched {modified_count} lines in {file_path}.')

if __name__ == '__main__':
    apply_patch()
