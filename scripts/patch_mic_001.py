def main():
    with open(CN_FILE, "r", encoding="utf-8") as f:
        lines = f.readlines()

    print(f"Total lines in {CN_FILE}: {len(lines)}")
    patched = 0
    for lno, text in PATCHES.items():
        idx = lno - 1
        cur = lines[idx]
        has_tab = "\t" in cur
        if has_tab:
            tag, old_cn = cur.rstrip("\r\n").split("\t", 1)
            if old_cn != text:
                lines[idx] = f"{tag}\t{text}\n"
                patched += 1
        else:
            old_cn = cur.rstrip("\r\n")
            if old_cn != text:
                lines[idx] = f"{text}\n"
                patched += 1

    with open(CN_FILE, "w", encoding="utf-8") as f:
        f.writelines(lines)

    print(f"Patched {patched} lines in mic_001.")


if __name__ == "__main__":
    main()
