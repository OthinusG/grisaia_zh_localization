def apply_patches():
    with open(CN_FILE, "r", encoding="utf-8") as f:
        lines = f.readlines()

    applied = 0
    for lno, new_text in PATCHES.items():
        idx = lno - 1
        if idx >= len(lines):
            print(f"Warning: Line index {idx} out of range")
            continue
        cur = lines[idx]
        if "\t" in cur:
            tag, _ = cur.split("\t", 1)
            lines[idx] = tag + "\t" + new_text + "\n"
        else:
            lines[idx] = new_text + "\n"
        applied += 1

    with open(CN_FILE, "w", encoding="utf-8") as f:
        f.writelines(lines)

    print(f"Successfully applied {applied} patches to {CN_FILE}")

if __name__ == "__main__":
    apply_patches()
